#!/usr/bin/env bash
# staging-grafana-edge.sh — the HTTP basic-auth gate at the Traefik edge in front of staging
# Grafana, https://grafana-staging.olajay.co.uk (issue #968 item 3; owner approval 2026-10-20,
# option A). It mirrors the testers' mail UI chain (plan 29-22, D-33) exactly.
#
# WHAT THE GATE IS
#   Grafana's login page was open to the internet, so anyone could throw password guesses at
#   the admin login. Traefik now answers 401 before Grafana sees the request. It enforces the
#   Ingress-NGINX provider's auth-type / auth-secret annotations (Ingress grafana-public) from
#   Secret grafana-edge-credentials (key `auth`, one apr1 htpasswd line for user
#   staging-operator), which the always-on secret-sync pod keeps synced from Key Vault through
#   SecretProviderClass grafana-edge-kv. Grafana's own admin login (grafana-admin-credentials)
#   is a SECOND credential behind this one; Traefik strips the Authorization header before
#   forwarding, so the two never meet. Prometheus scrapes Grafana through the Service, not the
#   Ingress, so the gate does not touch it.
#
#   The credential is GENERATED by scripts/staging-secrets.sh (class random alnum32 for
#   grafana-edge-credentials--password, composite htpasswd-apr1 for --auth). It is never
#   chosen by a human, never in git, never printed.
#
# USAGE
#   scripts/staging-grafana-edge.sh --list-kv-objects
#       prints grafana-edge-credentials--password: the PLAINTEXT object no SecretProviderClass
#       names (no workload is granted it), so scripts/lib/staging-secrets-common.sh ss_derive
#       lists it here and the write-once writer generates it.
#   scripts/staging-grafana-edge.sh --probe --context jtoye-stg-aks
#       the four read-only live arms G-1..G-4 (below). Needs, in the CALLER's environment,
#       JTOYE_AZURE_SUBSCRIPTION_ID=c483d353-5f61-4587-a790-addb9ab5fb94.
#   scripts/staging-grafana-edge.sh --selftest
#       every probe predicate FAILS on a planted wrong response and PASSES on the right one,
#       with stubbed curl/dig/kubectl/kubelogin/az: no cluster, no Azure, no network.
#
# THE ARMS (one line each, `ARM G-<n> PASS|FAIL <detail>`, then `PROBE: <p>/4 PASS|FAIL`)
#   G-1 GET /login with no credentials: 401 with a Basic WWW-Authenticate challenge, and the
#       body carries NO Grafana marker (EITHER marker is a leak).
#   G-2 GET /login with a fresh random WRONG password: 401, and no Grafana marker.
#   G-3 GET /login with the credential: 200 and Grafana's login page. "Grafana's page" is BOTH
#       markers measured off the running instance 2026-10-20 (Grafana v13.2.4): the document
#       title `<title>Grafana</title>` and the boot-data global `window.grafanaBootData`.
#   G-4 http://<host>/login (never with credentials): 301/302/307/308 to https://<host>/, and
#       the body carries no Grafana marker. Traefik's non-TLS router carries only the
#       redirect, so the credential is never sent over http.
#   Every request is pinned with curl --resolve to the ingress IP that dns1 was verified to
#   serve, so the endpoint probed is the endpoint checked (a stale /etc/hosts entry or a
#   split-horizon resolver cannot send the arms to another server).
#
# CREDENTIAL HANDLING
#   The password is read with az_read after az_guard_init in THIS shell, into a curl config
#   file (`user = "staging-operator:<pw>"`), mode 600, inside a mode-700 mktemp -d that an
#   EXIT trap removes; curl reads it with -K. Never `-u` on argv, never echoed. The wrong
#   password is a fresh random value handled the same way.
#
# EXIT: 0 every arm passed (or the non-probe mode succeeded), 1 an arm failed, 2 VOID /
#       usage (no resolution at dns1, missing tooling, a refused or mismatched context, an
#       unreadable Key Vault object).
set -uo pipefail

SCRIPT_PATH="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/$(basename "${BASH_SOURCE[0]}")"
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
IDENTITY_FILE="$REPO_ROOT/k8s/staging/azure-identity.yaml"
HOST="grafana-staging.olajay.co.uk"
EDGE_USER="staging-operator"
KV_PASSWORD_OBJECT="grafana-edge-credentials--password"
KV_VAULT="jtoye-stg-kv"
PAGE_PATH="/login"
MARKER_TITLE="<title>Grafana</title>"
MARKER_BOOT="window.grafanaBootData"
DNS1="dns1.registrar-servers.com"

usage_error() { echo "USAGE ERROR: $*" >&2; exit 2; }
void() { echo "VOID: $*" >&2; exit 2; }

ACTION="" CTX=""
while [ "$#" -gt 0 ]; do
  case "$1" in
    --list-kv-objects) ACTION=list ;;
    --probe) ACTION=probe ;;
    --selftest) ACTION=selftest ;;
    --context) shift; [ "$#" -gt 0 ] || usage_error "--context needs a name"; CTX="$1" ;;
    -h|--help) command sed -n '/^# USAGE/,/^# THE ARMS/p' "$SCRIPT_PATH" | command sed '$d; s/^# \{0,1\}//'; exit 0 ;;
    *) usage_error "unknown argument '$1'" ;;
  esac
  shift
done

# ---------------------------------------------------------------------------
# Judges: pure predicates over what the fetchers wrote into $W. Each prints one
# detail string and returns 0 PASS, 1 FAIL. No network, no cluster.
# ---------------------------------------------------------------------------
hdr() { command grep -i "^$2:" "$W/$1.hdr" 2>/dev/null | head -n 1 | tr -d '\r' | cut -d: -f2- | command sed 's/^ *//'; }
code() { cat "$W/$1.code" 2>/dev/null || echo 000; }
# Two readings of "this body is Grafana's", kept apart on purpose:
#   has_page  BOTH markers: the POSITIVE test (G-3). One alone could be a proxy error page
#             quoting a title, so it must not count as "we reached Grafana".
#   has_leak  EITHER marker: the NEGATIVE test (G-1, G-2, G-4). A refused response must carry
#             nothing of Grafana: boot data alone (build info and settings) or a title alone
#             is already a leak, and requiring both would let a partial page pass as refused.
has_page() { command grep -qF -- "$MARKER_TITLE" "$W/$1.body" 2>/dev/null && command grep -qF -- "$MARKER_BOOT" "$W/$1.body" 2>/dev/null; }
has_leak() { command grep -qF -- "$MARKER_TITLE" "$W/$1.body" 2>/dev/null || command grep -qF -- "$MARKER_BOOT" "$W/$1.body" 2>/dev/null; }

judge_g1() {
  local c w; c=$(code noauth); w=$(hdr noauth www-authenticate)
  echo "no credentials: HTTP $c, WWW-Authenticate '${w:-<none>}' grafana-content=$(has_leak noauth && echo yes || echo no)"
  [ "$c" = 401 ] && [[ "${w,,}" == basic* ]] && ! has_leak noauth
}
judge_g2() {
  local c; c=$(code wrongpw)
  echo "a random wrong password: HTTP $c grafana-content=$(has_leak wrongpw && echo yes || echo no)"
  [ "$c" = 401 ] && ! has_leak wrongpw
}
judge_g3() {
  local c; c=$(code root)
  echo "credential: GET $PAGE_PATH HTTP $c title=$(command grep -qF -- "$MARKER_TITLE" "$W/root.body" && echo yes || echo no) bootdata=$(command grep -qF -- "$MARKER_BOOT" "$W/root.body" && echo yes || echo no)"
  [ "$c" = 200 ] && has_page root
}
judge_g4() {
  local c l; c=$(code plainhttp); l=$(hdr plainhttp location)
  echo "http://$HOST$PAGE_PATH: HTTP $c Location '${l:-<none>}' grafana-content=$(has_leak plainhttp && echo yes || echo no)"
  case "$c" in 301|302|307|308) ;; *) return 1 ;; esac
  [[ "$l" == "https://$HOST/"* ]] && ! has_leak plainhttp
}

# ---------------------------------------------------------------------------
# Fetchers (the probe's only network reads). Responses go to $W.
# ---------------------------------------------------------------------------
fetch() { # NAME URL AUTH(none|right|wrong)
  local name="$1" url="$2" auth="$3" k=()
  case "$auth" in right) k=(-K "$W/right.curlrc") ;; wrong) k=(-K "$W/wrong.curlrc") ;; esac
  curl -sS --max-time 20 --resolve "$HOST:443:$IP" --resolve "$HOST:80:$IP" "${k[@]}" -o "$W/$name.body" -D "$W/$name.hdr" -w '%{http_code}' "$url" \
    > "$W/$name.code" 2> "$W/$name.err" || true
  [ -s "$W/$name.code" ] || echo 000 > "$W/$name.code"
}

probe() {
  local t p=0 n=0 rc r detail
  [ -n "$CTX" ] || usage_error "--context is required (no default: an ambient context is how a command lands on the wrong cluster)"
  for t in curl dig kubectl head od tr; do command -v "$t" > /dev/null 2>&1 || void "$t not on PATH"; done
  # shellcheck source=scripts/lib/staging-kube-guard.sh
  . "$REPO_ROOT/scripts/lib/staging-kube-guard.sh" || void "could not source staging-kube-guard.sh"
  rc=0; staging_kube_guard "$CTX" "$IDENTITY_FILE" || rc=$?
  [ "$rc" -eq 0 ] || exit 2
  IP=$(awk -F'"' '/^  ingress_ip_address:/ { print $2; exit }' "$IDENTITY_FILE")
  [ -n "$IP" ] || void "no ingress_ip_address in $IDENTITY_FILE"
  r=$(dig @"$DNS1" +short A "$HOST" 2> /dev/null | tail -n 1)
  [ "$r" = "$IP" ] || void "$HOST resolves to '${r:-<nothing>}' at $DNS1, not the ingress IP $IP"
  W=$(umask 077 && mktemp -d "${TMPDIR:-/tmp}/jtoye-grafanaedge.XXXXXXXX") || void "mktemp -d failed"
  chmod 700 "$W"
  trap 'rm -rf "$W"' EXIT
  # The credential: read in THIS shell, written only into a mode-600 curl config.
  # shellcheck source=scripts/lib/azure-guard.sh
  . "$REPO_ROOT/scripts/lib/azure-guard.sh" || void "could not source azure-guard.sh"
  rc=0; az_guard_init > /dev/null || rc=$?
  [ "$rc" -eq 0 ] || void "the subscription guard did not pass (rc=$rc)"
  local pw wrong
  pw=$(az_read keyvault secret show --vault-name "$KV_VAULT" -n "$KV_PASSWORD_OBJECT" --query value -o tsv 2> /dev/null) || pw=""
  [ -n "$pw" ] || void "could not read $KV_VAULT/$KV_PASSWORD_OBJECT"
  wrong=$(head -c 24 /dev/urandom | od -An -tx1 | tr -d ' \n')
  [ "$wrong" != "$pw" ] || void "the random wrong password equals the real one"
  (umask 077; printf 'user = "%s:%s"\n' "$EDGE_USER" "$pw" > "$W/right.curlrc"; printf 'user = "%s:%s"\n' "$EDGE_USER" "$wrong" > "$W/wrong.curlrc")
  pw=""; wrong=""

  fetch noauth "https://$HOST$PAGE_PATH" none
  fetch wrongpw "https://$HOST$PAGE_PATH" wrong
  fetch root "https://$HOST$PAGE_PATH" right
  fetch plainhttp "http://$HOST$PAGE_PATH" none

  for r in 1 2 3 4; do
    n=$((n + 1))
    detail=$("judge_g$r"); rc=$?
    if [ "$rc" -eq 0 ]; then echo "ARM G-$r PASS $detail"; p=$((p + 1)); else echo "ARM G-$r FAIL $detail"; fi
  done
  if [ "$p" -eq "$n" ]; then echo "PROBE: $p/$n PASS"; return 0; fi
  echo "PROBE: $p/$n FAIL"; return 1
}

# ---------------------------------------------------------------------------
# --selftest: stubbed tools; one planted wrong response per arm.
# ---------------------------------------------------------------------------
selftest() {
  local st real_bash fqdn ip mode want wantrc out rc caught bad=0 n=0 fmt="${GRAFANA_EDGE_SELFTEST_FORMAT:-plain}" tap=() line t
  real_bash=$(type -P bash) || void "bash not found"
  for t in awk od tr head sed grep cut mktemp; do command -v "$t" > /dev/null 2>&1 || void "selftest tool $t not found"; done
  st=$(umask 077 && mktemp -d "${TMPDIR:-/tmp}/jtoye-grafanaedge-st.XXXXXXXX") || void "mktemp -d failed"
  # shellcheck disable=SC2064
  trap "rm -rf '$st'" EXIT
  mkdir -p "$st/bin"
  fqdn=$(awk -F'"' '/^  aks_api_server_fqdn:/ { print $2; exit }' "$IDENTITY_FILE")
  ip=$(awk -F'"' '/^  ingress_ip_address:/ { print $2; exit }' "$IDENTITY_FILE")
  [ -n "$fqdn" ] && [ -n "$ip" ] || void "the identity file lacks aks_api_server_fqdn or ingress_ip_address"
  local pwstub="Stub0Password0For0The0Selftest0X"
  cat > "$st/bin/az" <<STUB
#!$real_bash
case " \$* " in
  *" account show "*) printf 'JToye Digital Production\tEnabled\n' ;;
  *" keyvault secret show "*" $KV_PASSWORD_OBJECT "*) printf '%s\n' "$pwstub" ;;
  *) echo "stub az: \$*" >&2; exit 9 ;;
esac
STUB
  cat > "$st/bin/kubelogin" <<STUB
#!$real_bash
exit 0
STUB
  cat > "$st/bin/dig" <<STUB
#!$real_bash
[ "\${STUB_MODE:-good}" = dns-wrong ] && { echo 203.0.113.7; exit 0; }
echo "$ip"
STUB
  cat > "$st/bin/kubectl" <<STUB
#!$real_bash
case " \$* " in
  *" config view "*) printf 'https://%s:443' "$fqdn" ;;
  *) echo "stub kubectl: \$*" >&2; exit 9 ;;
esac
STUB
  # curl: -K selects the credential (right/wrong by content), the URL the response.
  cat > "$st/bin/curl" <<STUB
#!$real_bash
mode="\${STUB_MODE:-good}"; url="" cfg="" out="" hdr="" w="" res=""
while [ \$# -gt 0 ]; do
  case "\$1" in
    -K) cfg="\$2"; shift ;; -o) out="\$2"; shift ;; -D) hdr="\$2"; shift ;;
    -w) w="\$2"; shift ;; --max-time) shift ;; --resolve) res="\$res \$2 "; shift ;; http*) url="\$1" ;;
  esac
  shift
done
auth=none
if [ -n "\$cfg" ]; then
  if command grep -qxF 'user = "$EDGE_USER:$pwstub"' "\$cfg"; then auth=right; else auth=wrong; fi
fi
page='<html><head><title>Grafana</title></head><body><script>window.grafanaBootData = {};</script></body></html>'
code=200 body="" h=""
# the request must be pinned to the verified ingress IP for ITS port; an unpinned one reached "another server"
case "\$url" in
  https://*) case "\$res" in *" $HOST:443:$ip "*) ;; *) url=unpinned ;; esac ;;
  http://*) case "\$res" in *" $HOST:80:$ip "*) ;; *) url=unpinned ;; esac ;;
esac
bootonly='<script>window.grafanaBootData = {};</script>'; titleonly='<html><head><title>Grafana</title></head></html>'
case "\$url" in
  unpinned) code=404; body="404 page not found (another server)" ;;
  http://*) if [ "\$mode" = g4-plain-page ]; then body="\$page"
            elif [ "\$mode" = g4-leaks-boot ]; then code=308; h="Location: https://$HOST/"; body="\$bootonly"
            elif [ "\$mode" = g4-leaks-title ]; then code=308; h="Location: https://$HOST/"; body="\$titleonly"
            elif [ "\$mode" = g4-redirect-http ]; then code=308; h="Location: http://$HOST/"
            else code=308; h="Location: https://$HOST/"; fi ;;
  *)
    if [ "\$auth" = none ] && [ "\$mode" != g1-open ]; then
      code=401; body="401 Unauthorized"
      [ "\$mode" = g1-no-challenge ] || h='WWW-Authenticate: Basic realm="staging"'
      [ "\$mode" = g1-leaks-page ] && body="\$page"
      [ "\$mode" = g1-leaks-boot ] && body="\$bootonly"
      [ "\$mode" = g1-leaks-title ] && body="\$titleonly"
    elif [ "\$auth" = wrong ] && [ "\$mode" != g2-wrong-accepted ]; then code=401; h='WWW-Authenticate: Basic realm="staging"'; body="401 Unauthorized"
      [ "\$mode" = g2-leaks-boot ] && body="\$bootonly"
      [ "\$mode" = g2-leaks-title ] && body="\$titleonly"
    elif [ "\$auth" = right ] && [ "\$mode" = g3-denied ]; then code=401; h='WWW-Authenticate: Basic realm="staging"'; body="401 Unauthorized"
    elif [ "\$mode" = g3-title-only ] && [ "\$auth" = right ]; then body='<html><head><title>Grafana</title></head></html>'
    elif [ "\$mode" = g3-other-app ] && [ "\$auth" = right ]; then body='<html><head><title>Mailpit</title></head></html>'
    else body="\$page"; fi ;;
esac
[ -n "\$hdr" ] && { printf 'HTTP/2 %s\r\n' "\$code"; [ -n "\$h" ] && printf '%s\r\n' "\$h"; printf '\r\n'; } > "\$hdr"
if [ -n "\$out" ] && [ "\$out" != /dev/null ]; then printf '%s' "\$body" > "\$out"; fi
case "\$w" in *'%{http_code}'*) printf '%s' "\$code" ;; esac
exit 0
STUB
  chmod +x "$st/bin/"*
  local -a ARMS=(good g1-open g1-no-challenge g1-leaks-page g1-leaks-boot g1-leaks-title g2-wrong-accepted g2-leaks-boot g2-leaks-title g3-denied g3-title-only g3-other-app g4-plain-page g4-leaks-boot g4-leaks-title g4-redirect-http dns-wrong list-kv-objects)
  declare -A WANT=(
    [good]="PROBE: 4/4 PASS" [g1-open]="ARM G-1 FAIL" [g1-no-challenge]="ARM G-1 FAIL" [g1-leaks-page]="ARM G-1 FAIL"
    [g1-leaks-boot]="ARM G-1 FAIL" [g1-leaks-title]="ARM G-1 FAIL" [g2-leaks-boot]="ARM G-2 FAIL" [g2-leaks-title]="ARM G-2 FAIL"
    [g4-leaks-boot]="ARM G-4 FAIL" [g4-leaks-title]="ARM G-4 FAIL"
    [g2-wrong-accepted]="ARM G-2 FAIL" [g3-denied]="ARM G-3 FAIL" [g3-title-only]="ARM G-3 FAIL" [g3-other-app]="ARM G-3 FAIL"
    [g4-plain-page]="ARM G-4 FAIL" [g4-redirect-http]="ARM G-4 FAIL"
    [dns-wrong]="VOID: $HOST resolves to '203.0.113.7'" [list-kv-objects]="$KV_PASSWORD_OBJECT"
  )
  declare -A WANT_RC=([good]=0 [dns-wrong]=2 [list-kv-objects]=0)
  for mode in "${ARMS[@]}"; do
    n=$((n + 1)); want="${WANT[$mode]}"; wantrc="${WANT_RC[$mode]:-1}"; line=""
    if [ "$mode" = list-kv-objects ]; then
      out=$("$real_bash" "$SCRIPT_PATH" --list-kv-objects 2>&1); rc=$?
      if [ "$rc" = 0 ] && [ "$out" = "$want" ]; then caught=yes; else caught=no; line="want exactly '$want' rc 0, got rc=$rc: $out"; fi
    else
      out=$(env PATH="$st/bin:$PATH" STUB_MODE="$mode" \
        JTOYE_AZURE_SUBSCRIPTION_ID=c483d353-5f61-4587-a790-addb9ab5fb94 KUBECONFIG=/dev/null \
        "$real_bash" "$SCRIPT_PATH" --probe --context jtoye-stg-aks 2>&1); rc=$?
      if [ "$rc" = "$wantrc" ] && command grep -qF -- "$want" <<< "$out"; then
        # a planted arm must fail ALONE: every other arm still passes
        if [ "$wantrc" = 1 ] && [ "$(command grep -c '^ARM G-[0-9] FAIL' <<< "$out")" != 1 ]; then
          caught=no; line="more than one arm failed: $(command grep '^ARM G-[0-9] FAIL' <<< "$out" | cut -c1-60 | tr '\n' ' ')"
        else caught=yes; fi
      else
        caught=no; line="want rc $wantrc and '$want', got rc=$rc: $(command grep -E '^(ARM|PROBE|VOID|USAGE|REFUSED)' <<< "$out" | head -n 3 | tr '\n' ' ')"
      fi
    fi
    [ "$caught" = yes ] || bad=$((bad + 1))
    if [ "$fmt" = tap ]; then
      if [ "$caught" = yes ]; then tap+=("ok $n - $mode"); else tap+=("not ok $n - $mode" "  ---" "  message: '${line//\'/}'" "  ..."); fi
    else
      echo "ARM $mode caught=$caught${line:+ ($line)}"
    fi
  done
  if [ "$fmt" = tap ]; then printf '%s\n' "TAP version 13" "1..$n" "${tap[@]}"; fi
  [ "$fmt" = tap ] && printf "# "; echo "SELFTEST: $((n - bad))/$n as expected"
  [ "$bad" -eq 0 ]
}

case "$ACTION" in
  list) echo "$KV_PASSWORD_OBJECT" ;;
  probe) probe; exit $? ;;
  selftest) selftest; exit $? ;;
  *) usage_error "one of --list-kv-objects, --probe --context CTX, --selftest" ;;
esac
