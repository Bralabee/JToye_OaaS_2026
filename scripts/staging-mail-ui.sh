  if command grep -qxF 'user = "$UI_USER:$pwstub"' "\$cfg"; then auth=right; else auth=wrong; fi
fi
shell='<html><head><title>Mailpit</title></head></html>'
code=200 body="" h=""
case "\$url" in
  http://*) if [ "\$mode" = ui4-plain-ui ]; then body="\$shell"; else code=308; h="Location: https://$HOST/"; fi ;;
  *)
    if [ "\$auth" = none ] && [ "\$mode" != ui1-open ]; then code=401; h='WWW-Authenticate: Basic realm="staging"'; body="401 Unauthorized"
    elif [ "\$auth" = wrong ] && [ "\$mode" != ui2-wrong-accepted ]; then code=401; h='WWW-Authenticate: Basic realm="staging"'; body="401 Unauthorized"
    else
      case "\$url" in
        */api/v1/search*) body='{"total":1,"messages":[{"ID":"StubId1","Subject":"x"}]}' ;;
        */api/v1/webui) if [ "\$mode" = ui7-relay ]; then body='{"MessageRelay":{"Enabled":true}}'; else body='{"MessageRelay":{"Enabled":false}}'; fi ;;
        */api/v1/send) if [ "\$mode" = ui7-send-open ]; then body='{"ID":"x"}'; else code=401; body="Unauthorised."; fi ;;
        */api/v1/info)
          echo x >> "$st/state/info.\$auth"; n=\$(wc -l < "$st/state/info.\$auth")
          if [ "\$mode" != ui8-no-429 ] && [ "\$auth" = right ] && [ "\$n" -gt 60 ]; then code=429; fi ;;
        *) body="\$shell" ;;
      esac
    fi ;;
esac
[ -n "\$hdr" ] && { printf 'HTTP/2 %s\r\n' "\$code"; [ -n "\$h" ] && printf '%s\r\n' "\$h"; printf '\r\n'; } > "\$hdr"
if [ -n "\$out" ] && [ "\$out" != /dev/null ]; then printf '%s' "\$body" > "\$out"; fi
case "\$w" in *'%{http_code}'*) printf '%s' "\$code"; case "\$w" in *'\n') echo ;; esac ;; esac
exit 0
STUB
  cat > "$st/bin/tcp-stub" <<STUB
#!$real_bash
[ "\$2" = 443 ] && exit 0
[ "\$2" = 1025 ] && [ "\${STUB_MODE:-good}" = ui5-smtp-open ] && exit 0
exit 1
STUB
  chmod +x "$st/bin/"*
  local -a ARMS=(good ui1-open ui2-wrong-accepted ui3-missing-id ui4-plain-ui ui5-smtp-open ui5-loadbalancer ui6-default-cert ui7-relay ui7-relay-env ui7-send-open ui8-no-429 dns-wrong list-kv-objects)
  declare -A WANT=(
    [good]="PROBE: 8/8 PASS" [ui1-open]="ARM UI-1 FAIL" [ui2-wrong-accepted]="ARM UI-2 FAIL" [ui3-missing-id]="ARM UI-3 FAIL"
    [ui4-plain-ui]="ARM UI-4 FAIL" [ui5-smtp-open]="ARM UI-5 FAIL" [ui5-loadbalancer]="ARM UI-5 FAIL" [ui6-default-cert]="ARM UI-6 FAIL"
    [ui7-relay]="ARM UI-7 FAIL" [ui7-relay-env]="ARM UI-7 FAIL" [ui7-send-open]="ARM UI-7 FAIL" [ui8-no-429]="ARM UI-8 FAIL"
    [dns-wrong]="VOID: $HOST resolves to '203.0.113.7'" [list-kv-objects]="$KV_PASSWORD_OBJECT"
  )
  declare -A WANT_RC=([good]=0 [dns-wrong]=2 [list-kv-objects]=0)
  for mode in "${ARMS[@]}"; do
    n=$((n + 1)); want="${WANT[$mode]}"; wantrc="${WANT_RC[$mode]:-1}"; line=""
    rm -f "$st/state/"*
    if [ "$mode" = list-kv-objects ]; then
      out=$("$real_bash" "$SCRIPT_PATH" --list-kv-objects 2>&1); rc=$?
      if [ "$rc" = 0 ] && [ "$out" = "$want" ]; then caught=yes; else caught=no; line="want exactly '$want' rc 0, got rc=$rc: $out"; fi
    else
      local extra=()
      [ "$mode" = ui3-missing-id ] && extra=(--expect-message-id NotTheStubId)
      out=$(env PATH="$st/bin:$PATH" STUB_MODE="$mode" MAIL_UI_TCP="$st/bin/tcp-stub" \
        JTOYE_AZURE_SUBSCRIPTION_ID=c483d353-5f61-4587-a790-addb9ab5fb94 KUBECONFIG=/dev/null \
        "$real_bash" "$SCRIPT_PATH" --probe --context jtoye-stg-aks "${extra[@]}" 2>&1); rc=$?
      if [ "$rc" = "$wantrc" ] && command grep -qF -- "$want" <<< "$out"; then
        # a planted arm must fail ALONE: every other arm still passes
        if [ "$wantrc" = 1 ] && [ "$(command grep -c '^ARM UI-[0-9] FAIL' <<< "$out")" != 1 ]; then
          caught=no; line="more than one arm failed: $(command grep '^ARM UI-[0-9] FAIL' <<< "$out" | cut -c1-60 | tr '\n' ' ')"
        else caught=yes; fi
      else
        caught=no; line="want rc $wantrc and '$want', got rc=$rc: $(command grep -E '^(ARM|PROBE|VOID|USAGE|REFUSED)' <<< "$out" | head -n 3 | tr '\n' ' ')"
      fi
    fi
    [ "$caught" = yes ] || bad=$((bad + 1))
    if [ "$fmt" = tap ]; then
      if [ "$caught" = yes ]; then tap+=("ok $n - $mode"); else tap+=("not ok $n - $mode" "  ---" "  message: '${line//\'/}'" "  ..."); fi
    else
      echo "ARM $mode caught=$caught${line:+ ($line)}"
    fi
  done
  if [ "$fmt" = tap ]; then printf '%s\n' "TAP version 13" "1..$n" "${tap[@]}"; fi
  [ "$fmt" = tap ] && printf "# "; echo "SELFTEST: $((n - bad))/$n as expected"
  [ "$bad" -eq 0 ]
}

case "$ACTION" in
  list) echo "$KV_PASSWORD_OBJECT" ;;
  probe) probe; exit $? ;;
  selftest) selftest; exit $? ;;
  *) usage_error "one of --list-kv-objects, --probe --context CTX [--expect-message-id ID], --selftest" ;;
esac
