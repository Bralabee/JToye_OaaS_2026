#!/usr/bin/env bash
# staging-mail-ui.sh — the testers' mail UI at https://mail-staging.olajay.co.uk (Phase 29
# plan 29-22, owner ruling D-33 of 2026-10-19; threats T-29-107..T-29-113).
#
# WHAT D-33 IS
#   Persona testers read the mail staging CAPTURES (verification, invitation and order
#   emails) in Mailpit's web UI and /api (port 8025), published on one host behind ONE
#   shared HTTP basic-auth credential. Traefik enforces it through the Ingress-NGINX
#   provider's auth-type / auth-secret annotations (Ingress mailpit-ui), from Secret
#   mailpit-ui-credentials (key `auth`, one apr1 htpasswd line for user staging-tester),
#   which the always-on secret-sync pod keeps synced from Key Vault through
#   SecretProviderClass mailpit-ui-kv. SMTP 1025 is never published.
#
#   The credential is GENERATED by scripts/staging-secrets.sh (class random alnum32 for
#   mailpit-ui-credentials--password, composite htpasswd-apr1 for --auth). It is never
#   chosen by a human, never in git, never printed. Whoever holds it reads EVERY staging
#   email, password-reset, staff-invite and DSAR-export links included, which is
#   equivalent to taking over any staging account. That is acceptable ONLY because staging
#   holds test personas and no real personal data (the tester note in k8s/DEPLOYMENT.md).
#
# USAGE
#   scripts/staging-mail-ui.sh --list-kv-objects
#       prints mailpit-ui-credentials--password: the PLAINTEXT object no SecretProviderClass
#       names (no workload is granted it), so scripts/lib/staging-secrets-common.sh ss_derive
#       lists it here and the write-once writer generates it.
#   scripts/staging-mail-ui.sh --probe --context jtoye-stg-aks [--expect-message-id ID]
#       the eight read-only live arms UI-1..UI-8 (below). Needs, in the CALLER's
#       environment, JTOYE_AZURE_SUBSCRIPTION_ID=c483d353-5f61-4587-a790-addb9ab5fb94.
#   scripts/staging-mail-ui.sh --selftest
#       every probe predicate FAILS on a planted wrong response and PASSES on the right one,
#       with stubbed curl/openssl/dig/kubectl/kubelogin/az and a stubbed TCP connect.
#
# THE ARMS (one line each, `ARM UI-<n> PASS|FAIL <detail>`, then `PROBE: <p>/8 PASS|FAIL`)
#   UI-1 GET / with no credentials: 401 with a Basic WWW-Authenticate challenge.
#   UI-2 GET / with a fresh random WRONG password: 401.
#   UI-3 GET / with the credential: 200 and Mailpit's UI shell (<title>Mailpit</title>, read
#        off the running instance 2026-10-19); GET /api/v1/search?query=to:<invite address>:
#        200 with total >= 1; with --expect-message-id, that ID is among the messages.
#   UI-4 http://<host>/ (never with credentials): 301/302/307/308 to https://<host>/, and the
#        body is not the UI. Traefik's non-TLS router carries only the redirect, so the
#        credential is never sent over http (T-29-113).
#   UI-5 a TCP connect to 1025 FAILS on the ingress IP and on the host, while 443 on the
#        host connects (if that control fails: VOID); Traefik's Service ports are exactly
#        80 and 443, and no jtoye-staging Service is LoadBalancer or NodePort (T-29-109).
#   UI-6 the certificate served for the host is issued by O=Let's Encrypt and names the
#        host; control: an unknown SNI on the same IP is served TRAEFIK DEFAULT CERT (if
#        not, VOID: the read could not tell the two apart).
#   UI-7 Mailpit sends nothing: authenticated GET /api/v1/webui reports
#        MessageRelay.Enabled false, an authenticated POST /api/v1/send answers 401 (its
#        Send API credential is random per pod and held by nobody), and the Ready mailpit
#        pod's env carries none of the relay/forward/accept-any/chaos names and exactly one
#        MP_SEND_API_AUTH_FILE.
#   UI-8 300 authenticated GETs of /api/v1/info, 20 in parallel, meet at least one 429 (the
#        edge limiter is live AFTER auth). The same burst without credentials is printed as
#        `UNAUTH-429=<n>` and not asserted: Traefik v3.7.15 orders basic auth BEFORE the
#        rate limiter, so failed guesses are predicted not to be throttled (T-29-111).
#
# CREDENTIAL HANDLING (T-29-112)
#   The password is read with az_read after az_guard_init in THIS shell, into a curl config
#   file (`user = "staging-tester:<pw>"`), mode 600, inside a mode-700 mktemp -d that an
#   EXIT trap removes; curl reads it with -K. Never `-u` on argv, never echoed. The wrong
#   password is a fresh random value handled the same way.
#
# EXIT: 0 every arm passed (or the non-probe mode succeeded), 1 an arm failed, 2 VOID /
#       usage (no resolution at dns1, missing tooling, a refused or mismatched context, an
#       unreadable Key Vault object, a control that did not hold).
set -uo pipefail

SCRIPT_PATH="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/$(basename "${BASH_SOURCE[0]}")"
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
IDENTITY_FILE="$REPO_ROOT/k8s/staging/azure-identity.yaml"
HOST="mail-staging.olajay.co.uk"
CONTROL_SNI="unknown-staging.olajay.co.uk"
UI_USER="staging-tester"
KV_PASSWORD_OBJECT="mailpit-ui-credentials--password"
KV_VAULT="jtoye-stg-kv"
NS="jtoye-staging"
INVITE_TO="staff.invite.staging@olajay.co.uk"
UI_SHELL="<title>Mailpit</title>"
DNS1="dns1.registrar-servers.com"
FORBIDDEN_ENV="MP_SMTP_RELAY_CONFIG MP_SMTP_RELAY_ALL MP_SMTP_RELAY_MATCHING MP_SMTP_FORWARD_CONFIG MP_SEND_API_AUTH_ACCEPT_ANY MP_ENABLE_CHAOS"

usage_error() { echo "USAGE ERROR: $*" >&2; exit 2; }
void() { echo "VOID: $*" >&2; exit 2; }

ACTION="" CTX="" EXPECT_ID=""
while [ "$#" -gt 0 ]; do
  case "$1" in
    --list-kv-objects) ACTION=list ;;
    --probe) ACTION=probe ;;
    --selftest) ACTION=selftest ;;
    --context) shift; [ "$#" -gt 0 ] || usage_error "--context needs a name"; CTX="$1" ;;
    --expect-message-id) shift; [ "$#" -gt 0 ] || usage_error "--expect-message-id needs an ID"; EXPECT_ID="$1" ;;
    -h|--help) command sed -n '/^# USAGE/,/^# THE ARMS/p' "$SCRIPT_PATH" | command sed '$d; s/^# \{0,1\}//'; exit 0 ;;
    *) usage_error "unknown argument '$1'" ;;
  esac
  shift
done

# ---------------------------------------------------------------------------
# Judges: pure predicates over what the fetchers wrote into $W. Each prints one
# detail string and returns 0 PASS, 1 FAIL, 2 VOID. No network, no cluster.
# ---------------------------------------------------------------------------
hdr() { command grep -i "^$2:" "$W/$1.hdr" 2>/dev/null | head -n 1 | tr -d '\r' | cut -d: -f2- | command sed 's/^ *//'; }
code() { cat "$W/$1.code" 2>/dev/null || echo 000; }
has_shell() { command grep -qF -- "$UI_SHELL" "$W/$1.body" 2>/dev/null; }

judge_ui1() {
  echo "STUB: not implemented"; return 0
  local c w; c=$(code noauth); w=$(hdr noauth www-authenticate)
  echo "no credentials: HTTP $c, WWW-Authenticate '${w:-<none>}'"
  [ "$c" = 401 ] && [[ "${w,,}" == basic* ]] && ! has_shell noauth
}
judge_ui2() {
  echo "STUB: not implemented"; return 0
  local c; c=$(code wrongpw)
  echo "a random wrong password: HTTP $c"
  [ "$c" = 401 ] && ! has_shell wrongpw
}
judge_ui3() {
  echo "STUB: not implemented"; return 0
  local c s total ids found=yes
  c=$(code root); s=$(code search)
  total=$(jq -r '.total // empty' "$W/search.body" 2>/dev/null)
  if [ -n "$EXPECT_ID" ]; then
    ids=$(jq -r '.messages[]?.ID' "$W/search.body" 2>/dev/null)
    command grep -qxF -- "$EXPECT_ID" <<< "$ids" || found=no
  fi
  echo "credential: GET / HTTP $c shell=$(has_shell root && echo yes || echo no); search to:$INVITE_TO HTTP $s total=${total:-?}${EXPECT_ID:+ expected-id=$EXPECT_ID found=$found}"
  [ "$c" = 200 ] && has_shell root && [ "$s" = 200 ] && [[ "$total" =~ ^[0-9]+$ ]] && [ "$total" -ge 1 ] && [ "$found" = yes ]
}
judge_ui4() {
  echo "STUB: not implemented"; return 0
  local c l; c=$(code plainhttp); l=$(hdr plainhttp location)
  echo "http://$HOST/: HTTP $c Location '${l:-<none>}' shell=$(has_shell plainhttp && echo yes || echo no)"
  case "$c" in 301|302|307|308) ;; *) return 1 ;; esac
  [[ "$l" == "https://$HOST/"* ]] && ! has_shell plainhttp
}
judge_ui5() {
  echo "STUB: not implemented"; return 0
  local ip1025 host1025 host443 ports lbs
  ip1025=$(cat "$W/tcp.ip1025"); host1025=$(cat "$W/tcp.host1025"); host443=$(cat "$W/tcp.host443")
  ports=$(cat "$W/traefik.ports"); lbs=$(cat "$W/ns.exposed")
  echo "tcp ip:1025=$ip1025 host:1025=$host1025 host:443=$host443 (control); traefik ports [$ports]; $NS LoadBalancer/NodePort services=$lbs"
  [ "$host443" = connected ] || return 2
  [ "$ip1025" = failed ] && [ "$host1025" = failed ] && [ "$ports" = "80 443" ] && [ "$lbs" = 0 ]
}
judge_ui6() {
  echo "STUB: not implemented"; return 0
  local mine ctl
  mine=$(tr '\n' ' ' < "$W/cert.host"); ctl=$(tr '\n' ' ' < "$W/cert.control")
  echo "SNI $HOST: ${mine:-<nothing>}| control SNI $CONTROL_SNI: ${ctl:-<nothing>}"
  [[ "$ctl" == *"TRAEFIK DEFAULT CERT"* ]] || return 2
  [[ "$mine" == *"O=Let's Encrypt"* ]] && [[ "$mine" == *"$HOST"* ]] && [[ "$mine" != *"TRAEFIK DEFAULT CERT"* ]]
}
judge_ui7() {
  echo "STUB: not implemented"; return 0
  local relay send forb lock n
  relay=$(jq -r '.MessageRelay.Enabled' "$W/webui.body" 2>/dev/null); send=$(code send)
  # Every relay/forward variable (MP_SMTP_RELAY_*, MP_SMTP_FORWARD_*, a superset of
  # FORBIDDEN_ENV's four) plus accept-any and chaos.
  forb=$(command grep -cE '^(MP_SMTP_RELAY_[A-Z_]+|MP_SMTP_FORWARD_[A-Z_]+|MP_SEND_API_AUTH_ACCEPT_ANY|MP_ENABLE_CHAOS)$' "$W/mailpit.env")
  lock=$(command grep -cxF MP_SEND_API_AUTH_FILE "$W/mailpit.env")
  echo "webui HTTP $(code webui) MessageRelay.Enabled=${relay:-?}; authenticated POST /api/v1/send HTTP $send; Ready pod $(cat "$W/mailpit.pod") forbidden-env=$forb MP_SEND_API_AUTH_FILE=$lock"
  [ "$(code webui)" = 200 ] && [ "$relay" = false ] && [ "$send" = 401 ] && [ "$forb" = 0 ] && [ "$lock" = 1 ]
}
judge_ui8() {
  echo "STUB: not implemented"; return 0
  local a u
  a=$(command grep -c '^429$' "$W/burst.auth"); u=$(command grep -c '^429$' "$W/burst.noauth")
  echo "authenticated burst 300x/20: 429=$a of $(command grep -c . "$W/burst.auth"); UNAUTH-429=$u"
  [ "$a" -ge 1 ]
}

# ---------------------------------------------------------------------------
# Fetchers (the probe's only network and cluster reads). Responses go to $W.
# ---------------------------------------------------------------------------
fetch() { # NAME URL AUTH(none|right|wrong) [METHOD] [JSON]
  local name="$1" url="$2" auth="$3" method="${4:-GET}" body="${5:-}" k=()
  case "$auth" in right) k=(-K "$W/right.curlrc") ;; wrong) k=(-K "$W/wrong.curlrc") ;; esac
  if [ -n "$body" ]; then
    curl -sS --max-time 20 "${k[@]}" -X "$method" -H 'Content-Type: application/json' --data "$body" \
      -o "$W/$name.body" -D "$W/$name.hdr" -w '%{http_code}' "$url" > "$W/$name.code" 2> "$W/$name.err" || true
  else
    curl -sS --max-time 20 "${k[@]}" -X "$method" -o "$W/$name.body" -D "$W/$name.hdr" -w '%{http_code}' "$url" \
      > "$W/$name.code" 2> "$W/$name.err" || true
  fi
  [ -s "$W/$name.code" ] || echo 000 > "$W/$name.code"
}
tcp_try() { timeout 8 bash -c 'exec 3<>"/dev/tcp/$0/$1"' "$1" "$2" > /dev/null 2>&1; }
tcp() { local f="$1"; shift; if "${MAIL_UI_TCP:-tcp_try}" "$@"; then echo connected > "$W/$f"; else echo failed > "$W/$f"; fi; }
cert() { # FILE SNI
  openssl s_client -connect "$IP:443" -servername "$2" < /dev/null 2> /dev/null \
    | openssl x509 -noout -issuer -subject -ext subjectAltName -nameopt RFC2253 2> /dev/null > "$W/$1" || true
}
burst() { # FILE AUTH
  local k=() i
  [ "$2" = right ] && k=(-K "$W/right.curlrc")
  for i in $(seq 1 300); do echo "$i"; done \
    | xargs -P 20 -I{} curl -s --max-time 20 "${k[@]}" -o /dev/null -w '%{http_code}\n' "https://$HOST/api/v1/info" > "$W/$1" 2> /dev/null || true
}

probe() {
  local t p=0 n=0 rc r detail ctxs
  [ -n "$CTX" ] || usage_error "--context is required (no default: an ambient context is how a command lands on the wrong cluster)"
  for t in curl openssl dig kubectl jq xargs timeout; do command -v "$t" > /dev/null 2>&1 || void "$t not on PATH"; done
  # shellcheck source=scripts/lib/staging-kube-guard.sh
  . "$REPO_ROOT/scripts/lib/staging-kube-guard.sh" || void "could not source staging-kube-guard.sh"
  rc=0; staging_kube_guard "$CTX" "$IDENTITY_FILE" || rc=$?
  [ "$rc" -eq 0 ] || exit 2
  IP=$(awk -F'"' '/^  ingress_ip_address:/ { print $2; exit }' "$IDENTITY_FILE")
  [ -n "$IP" ] || void "no ingress_ip_address in $IDENTITY_FILE"
  r=$(dig @"$DNS1" +short A "$HOST" 2> /dev/null | tail -n 1)
  [ "$r" = "$IP" ] || void "$HOST resolves to '${r:-<nothing>}' at $DNS1, not the ingress IP $IP"
  W=$(umask 077 && mktemp -d "${TMPDIR:-/tmp}/jtoye-mailui.XXXXXXXX") || void "mktemp -d failed"
  chmod 700 "$W"
  trap 'rm -rf "$W"' EXIT
  # The credential: read in THIS shell, written only into a mode-600 curl config.
  # shellcheck source=scripts/lib/azure-guard.sh
  . "$REPO_ROOT/scripts/lib/azure-guard.sh" || void "could not source azure-guard.sh"
  rc=0; az_guard_init > /dev/null || rc=$?
  [ "$rc" -eq 0 ] || void "the subscription guard did not pass (rc=$rc)"
  local pw wrong
  pw=$(az_read keyvault secret show --vault-name "$KV_VAULT" -n "$KV_PASSWORD_OBJECT" --query value -o tsv 2> /dev/null) || pw=""
  [ -n "$pw" ] || void "could not read $KV_VAULT/$KV_PASSWORD_OBJECT"
  wrong=$(head -c 24 /dev/urandom | od -An -tx1 | tr -d ' \n')
  [ "$wrong" != "$pw" ] || void "the random wrong password equals the real one"
  (umask 077; printf 'user = "%s:%s"\n' "$UI_USER" "$pw" > "$W/right.curlrc"; printf 'user = "%s:%s"\n' "$UI_USER" "$wrong" > "$W/wrong.curlrc")
  pw=""; wrong=""

  fetch noauth "https://$HOST/" none
  fetch wrongpw "https://$HOST/" wrong
  fetch root "https://$HOST/" right
  fetch search "https://$HOST/api/v1/search?query=to:$INVITE_TO" right
  fetch plainhttp "http://$HOST/" none
  tcp tcp.ip1025 "$IP" 1025; tcp tcp.host1025 "$HOST" 1025; tcp tcp.host443 "$HOST" 443
  kubectl --context "$CTX" -n traefik get svc traefik -o jsonpath='{range .spec.ports[*]}{.port}{" "}{end}' 2> /dev/null \
    | tr ' ' '\n' | command grep . | LC_ALL=C sort -n | tr '\n' ' ' | command sed 's/ $//' > "$W/traefik.ports"
  kubectl --context "$CTX" -n "$NS" get svc -o jsonpath='{range .items[*]}{.spec.type}{"\n"}{end}' > "$W/ns.types" 2> /dev/null \
    || void "could not list the $NS Services"
  [ -s "$W/ns.types" ] || void "the $NS Service list is empty"
  command grep -cE '^(LoadBalancer|NodePort)$' "$W/ns.types" > "$W/ns.exposed"
  cert cert.host "$HOST"; cert cert.control "$CONTROL_SNI"
  fetch webui "https://$HOST/api/v1/webui" right
  fetch send "https://$HOST/api/v1/send" right POST \
    '{"From":{"Email":"probe@staging.invalid"},"To":[{"Email":"probe@staging.invalid"}],"Subject":"UI-7 send-api probe","Text":"must be refused"}'
  kubectl --context "$CTX" -n "$NS" get pods -l app=mailpit \
    -o jsonpath='{range .items[*]}{.metadata.name}{" "}{.status.conditions[?(@.type=="Ready")].status}{"\n"}{end}' > "$W/mailpit.pods" 2> /dev/null
  awk '$2 == "True" { print $1; exit }' "$W/mailpit.pods" > "$W/mailpit.pod"
  [ -s "$W/mailpit.pod" ] || void "no Ready mailpit pod"
  kubectl --context "$CTX" -n "$NS" get pod "$(cat "$W/mailpit.pod")" \
    -o jsonpath='{range .spec.containers[?(@.name=="mailpit")].env[*]}{.name}{"\n"}{end}' > "$W/mailpit.env" 2> /dev/null
  [ -s "$W/mailpit.env" ] || void "the Ready mailpit pod's env could not be read"
  burst burst.auth right
  burst burst.noauth none

  for r in 1 2 3 4 5 6 7 8; do
    n=$((n + 1))
    detail=$("judge_ui$r"); rc=$?
    case "$rc" in
      0) echo "ARM UI-$r PASS $detail"; p=$((p + 1)) ;;
      2) echo "ARM UI-$r VOID $detail"; void "UI-$r's control did not hold" ;;
      *) echo "ARM UI-$r FAIL $detail" ;;
    esac
  done
  echo "UNAUTH-429=$(command grep -c '^429$' "$W/burst.noauth")"
  if [ "$p" -eq "$n" ]; then echo "PROBE: $p/$n PASS"; return 0; fi
  echo "PROBE: $p/$n FAIL"; return 1
}

# ---------------------------------------------------------------------------
# --selftest: stubbed tools; one planted wrong response per arm.
# ---------------------------------------------------------------------------
selftest() {
  local st real_bash fqdn ip mode want wantrc out rc caught bad=0 n=0 fmt="${MAIL_UI_SELFTEST_FORMAT:-plain}" tap=() line
  real_bash=$(type -P bash) || void "bash not found"
  for t in jq awk xargs od tr head seq sort sed grep cut mktemp; do command -v "$t" > /dev/null 2>&1 || void "selftest tool $t not found"; done
  st=$(umask 077 && mktemp -d "${TMPDIR:-/tmp}/jtoye-mailui-st.XXXXXXXX") || void "mktemp -d failed"
  # shellcheck disable=SC2064
  trap "rm -rf '$st'" EXIT
  mkdir -p "$st/bin" "$st/state"
  fqdn=$(awk -F'"' '/^  aks_api_server_fqdn:/ { print $2; exit }' "$IDENTITY_FILE")
  ip=$(awk -F'"' '/^  ingress_ip_address:/ { print $2; exit }' "$IDENTITY_FILE")
  [ -n "$fqdn" ] && [ -n "$ip" ] || void "the identity file lacks aks_api_server_fqdn or ingress_ip_address"
  local pwstub="Stub0Password0For0The0Selftest0X"
  cat > "$st/bin/az" <<STUB
#!$real_bash
case " \$* " in
  *" account show "*) printf 'JToye Digital Production\tEnabled\n' ;;
  *" keyvault secret show "*" $KV_PASSWORD_OBJECT "*) printf '%s\n' "$pwstub" ;;
  *) echo "stub az: \$*" >&2; exit 9 ;;
esac
STUB
  cat > "$st/bin/kubelogin" <<STUB
#!$real_bash
exit 0
STUB
  cat > "$st/bin/dig" <<STUB
#!$real_bash
[ "\${STUB_MODE:-good}" = dns-wrong ] && { echo 203.0.113.7; exit 0; }
echo "$ip"
STUB
  cat > "$st/bin/kubectl" <<STUB
#!$real_bash
a=" \$* "
case "\$a" in
  *" config view "*) printf 'https://%s:443' "$fqdn" ;;
  *" -n traefik get svc traefik "*) printf '80 443 ' ;;
  *" get svc -o jsonpath"*) printf 'ClusterIP\nClusterIP\n'; if [ "\${STUB_MODE:-good}" = ui5-loadbalancer ]; then printf 'LoadBalancer\n'; fi ;;
  *" get pods -l app=mailpit "*) printf 'mailpit-stub True\n' ;;
  *" get pod mailpit-stub "*)
    printf 'MP_SMTP_TLS_CERT\nMP_SMTP_TLS_KEY\nMP_SMTP_REQUIRE_STARTTLS\nMP_DATABASE\nMP_SEND_API_AUTH_FILE\n'
    if [ "\${STUB_MODE:-good}" = ui7-relay-env ]; then printf 'MP_SMTP_RELAY_ALL\n'; fi ;;
  *) echo "stub kubectl: \$*" >&2; exit 9 ;;
esac
STUB
  cat > "$st/bin/openssl" <<STUB
#!$real_bash
case "\$1" in
  s_client) while [ \$# -gt 0 ]; do [ "\$1" = -servername ] && echo "STUB-SNI \$2"; shift; done ;;
  x509)
    sni=\$(awk '/^STUB-SNI / { print \$2 }')
    if [ "\$sni" = "$HOST" ] && [ "\${STUB_MODE:-good}" != ui6-default-cert ]; then
      printf "issuer=CN=R13,O=Let's Encrypt,C=US\nsubject=CN=$HOST\nX509v3 Subject Alternative Name: \n    DNS:$HOST\n"
    else
      printf 'issuer=CN=TRAEFIK DEFAULT CERT\nsubject=CN=TRAEFIK DEFAULT CERT\n'
    fi ;;
  *) echo "stub openssl: \$*" >&2; exit 9 ;;
esac
STUB
  # curl: -K selects the credential (right/wrong by content), the URL the response.
  cat > "$st/bin/curl" <<STUB
#!$real_bash
mode="\${STUB_MODE:-good}"; url="" cfg="" method=GET out="" hdr="" w=""
while [ \$# -gt 0 ]; do
  case "\$1" in
    -K) cfg="\$2"; shift ;; -X) method="\$2"; shift ;; -o) out="\$2"; shift ;; -D) hdr="\$2"; shift ;;
    -w) w="\$2"; shift ;; -H|--data|--max-time) shift ;; http*) url="\$1" ;;
  esac
  shift
done
